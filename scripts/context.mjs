// Builds the agent context file a profile renders. Shared by render.mjs (writes it) and
// doctor.mjs (checks the rendered copy still matches, since inlined copies go stale).

import { readFileSync } from "node:fs";
import { join } from "node:path";

export function contextFile(profile, root, target) {
  if (!profile.context?.length) return null;
  const banner = `<!-- GENERATED by ${join(root, "scripts/render.mjs")} — edit the source repository, not this file. -->`;
  if (profile.kind === "claude") {
    // @-imports keep this zero-drift: the harness reads the source files directly and labels each
    // with its path, so repo-relative paths in them stay resolvable.
    const body = [banner, "", ...profile.context.map((c) => `@${join(root, c)}`), ""].join("\n");
    return { path: join(target, "CLAUDE.md"), body };
  }
  // No import mechanism, so content is inlined. Repo-relative pointers to files that are not
  // inlined become absolute, or the agent has no way to find them.
  const parts = profile.context.map((c) =>
    readFileSync(join(root, c), "utf8").trim().replaceAll("`memory/", `\`${root}/memory/`),
  );
  const body = [banner, "", parts.join("\n\n---\n\n"), ""].join("\n");
  return { path: join(target, "AGENTS.md"), body };
}
